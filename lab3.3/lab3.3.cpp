#include <iostream>

using namespace std;

int main() 
{
    setlocale(LC_ALL, "Russian");

    int pulse;

    do 
    {
        cout << "Введите пульс покоя (от 30 до 120): ";
        cin >> pulse;

        if (pulse < 30 || pulse > 120) 
        {
            cout << "Некорректный ввод. Попробуйте снова." << endl;
        }
    } while (pulse < 30 || pulse > 120); 

    
    if (pulse < 60) 
    {
        cout << "Пульс меньше 60." << endl;
    }
    else if (pulse >= 60 && pulse <= 80) 
    {
        cout << "Пульс от 60 до 80 включительно." << endl;
    }
    else 
    {
        cout << "Пульс выше 80." << endl;
    }

    return 0;
}

